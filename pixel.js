  const ROWS = 9;
  const OK = /^[A-Za-z0-9&.!?\-–+\/:'()>#$%*< ]+$/;
  const CELL = 0.88; // ขนาดช่องพิกเซล (ที่เหลือคือร่อง)

  function wordSvg(word) {
    const chars = [...word.toUpperCase()].filter((ch) => GLYPH[ch]);
    if (!chars.length) return "";
    let rects = "";
    let ox = 0;
    chars.forEach((ch) => {
      const rows = GLYPH[ch];
      rows.forEach((row, y) => [...row].forEach((bit, x) => {
        if (bit === "#") rects += `<rect x="${ox + x}" y="${y}" width="${CELL}" height="${CELL}"/>`;
      }));
      ox += rows[0].length + 1; // เว้น 1 ช่องระหว่างตัว
    });
    const w = ox - 1;
    return `<svg class="px-word" viewBox="0 0 ${w} ${ROWS}" style="aspect-ratio:${w}/${ROWS}" aria-hidden="true" focusable="false">${rects}</svg>`;
  }

  /** วาดข้อความลงใน .px (ใช้ซ้ำได้ เช่น ตอนสลับตัวอักษร) */
  function set(px, text) {
    const words = text.split(/(\s+)/).filter(Boolean);
    const art = px.querySelector(".px-art");
    art.innerHTML = words.map((w) => (/^\s+$/.test(w) ? '<i class="px-space"> </i>' : wordSvg(w))).join("");
  }

  function pixelize(el) {
    if (el.dataset.pixel) return;
    const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT, {
      acceptNode: (n) => (n.parentElement.closest(".sr-only, .stripes, svg") ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    const texts = nodes.map((n) => n.nodeValue.trim()).filter(Boolean);
    if (!texts.length || !texts.every((t) => OK.test(t))) return; // มีภาษาไทยหรือสัญลักษณ์อื่น ปล่อยไว้แบบเดิม
    el.dataset.pixel = "1";
    for (const n of nodes) {
      const text = n.nodeValue.trim();
      if (!text) continue;
      const px = document.createElement("span");
      px.className = "px";
      px.dataset.text = text;
      px.innerHTML = `<span class="px-art"></span><span class="sr-only"></span>`;
      px.querySelector(".sr-only").textContent = text;
      set(px, text);
      n.replaceWith(px);
    }
  }

